import { CATEGORIES, getFormGroups } from '../data/product-schema.js';
import { escapeHtml } from '../utils/dom.js';
import { formatDateTime } from '../utils/formatting.js';
import { ACCEPTED_MEDIA, IMAGE_MAX_BYTES, MEDIA_LIMIT, MAX_VIDEO_SECONDS, VIDEO_MAX_BYTES } from '../utils/validation.js';

function getValue(field, product, defaultCurrency) {
  if (!product) return field.key === 'currency' ? defaultCurrency || '' : '';
  if (field.variationKey) return product.variations?.[field.variationKey] ?? '';
  return product[field.key] ?? '';
}

function renderSelect(field, value, choices, placeholder) {
  const selected = value === true ? 'true' : value === false ? 'false' : String(value ?? '');
  return `<div class="form-field"><label class="form-label" for="field-${escapeHtml(field.key)}">${escapeHtml(field.label)}${field.required ? '<span class="required-mark" aria-label="required">*</span>' : ''}</label><select id="field-${escapeHtml(field.key)}" name="${escapeHtml(field.key)}" ${field.required ? 'required aria-required="true"' : ''}><option value="" disabled ${selected === '' ? 'selected' : ''}>${escapeHtml(placeholder)}</option>${choices.map(({ value: optionValue, label }) => `<option value="${escapeHtml(optionValue)}" ${selected === String(optionValue) ? 'selected' : ''}>${escapeHtml(label)}</option>`).join('')}</select><span class="field-error" data-field-error="${escapeHtml(field.key)}" aria-live="polite"></span></div>`;
}

function renderField(field, product, { currencies = [], defaultCurrency = '' } = {}) {
  const value = getValue(field, product, defaultCurrency);
  const fieldKey = escapeHtml(field.key);
  const fieldId = `field-${fieldKey}`;
  const required = field.required ? 'required aria-required="true"' : '';
  const label = `<label class="form-label" for="${fieldId}">${escapeHtml(field.label)}${field.required ? '<span class="required-mark" aria-label="required">*</span>' : ''}</label>`;
  const error = `<span class="field-error" data-field-error="${fieldKey}" aria-live="polite"></span>`;
  const hint = field.key === 'sku'
    ? '<span class="field-hint">Generated by the backend when the product is saved. It cannot be edited.</span>'
    : field.key === 'slug'
      ? '<span class="field-hint">Generated from the product name by the backend.</span>'
      : '';

  if (field.type === 'media') {
    return `<div class="form-field form-field-wide media-field" data-media-field>${label}<p class="field-hint media-hint">The server converts images to AVIF and videos to WebM. Add up to ${MEDIA_LIMIT} files total (images up to ${Math.round(IMAGE_MAX_BYTES / (1024 * 1024))} MB each; videos up to ${Math.round(VIDEO_MAX_BYTES / (1024 * 1024))} MB and ${MAX_VIDEO_SECONDS} seconds).</p><div class="media-list" data-media-list></div><label class="media-drop-zone" for="media-input" data-drop-zone><input id="media-input" class="visually-hidden" type="file" accept="${escapeHtml(ACCEPTED_MEDIA)}" multiple data-media-input /><span class="upload-icon">＋</span><strong>Add images or videos</strong><small>Browse files or drop up to ${MEDIA_LIMIT} files here</small></label><span class="media-counter" data-media-counter>0 of ${MEDIA_LIMIT} files added</span>${error}</div>`;
  }

  if (field.systemManaged) {
    const display = field.type === 'datetime' && value ? formatDateTime(value) : value || (product ? 'Not available' : 'Generated when saved');
    return `<div class="form-field system-field"><span class="form-label">${escapeHtml(field.label)}</span><div class="system-value" aria-readonly="true">${escapeHtml(display)}</div>${hint || '<span class="field-hint">System-managed.</span>'}</div>`;
  }

  if (field.type === 'textarea') {
    const rows = field.key === 'description' ? 4 : 2;
    const placeholder = field.key === 'description' ? 'Product details' : 'Optional short summary';
    return `<div class="form-field form-field-wide">${label}<textarea id="${fieldId}" name="${fieldKey}" rows="${rows}" maxlength="${field.key === 'description' ? 20000 : 1000}" placeholder="${placeholder}" ${required}>${escapeHtml(value)}</textarea>${error}</div>`;
  }

  if (field.type === 'tags') {
    return `<div class="form-field">${label}<input id="${fieldId}" name="tags" type="text" value="${escapeHtml(Array.isArray(value) ? value.join(', ') : value)}" placeholder="e.g. new, best seller" /><span class="field-hint">Separate up to 50 tags with commas.</span>${error}</div>`;
  }

  if (field.type === 'currency') {
    const list = [...new Set([...(currencies || []), ...(value ? [value] : [])])];
    return renderSelect(field, value, list.map((code) => ({ value: code, label: code })), 'Choose currency');
  }

  if (field.type === 'status') {
    return renderSelect(field, value, [
      { value: 'draft', label: 'Draft' },
      { value: 'active', label: 'Active' },
    ], 'Choose status');
  }

  if (field.type === 'boolean') {
    return renderSelect(field, value, [
      { value: 'true', label: 'Yes' },
      { value: 'false', label: 'No' },
    ], 'Choose yes or no');
  }

  if (field.key === 'category') {
    const categories = [...new Set([...CATEGORIES, ...(value && !CATEGORIES.includes(value) ? [value] : [])])];
    return `<div class="form-field">${label}<input id="${fieldId}" name="category" type="text" list="product-categories" value="${escapeHtml(value)}" placeholder="Optional category" /><datalist id="product-categories">${categories.map((category) => `<option value="${escapeHtml(category)}"></option>`).join('')}</datalist><span class="field-hint">Optional; used to generate the SKU prefix.</span>${error}</div>`;
  }

  const numeric = field.type === 'decimal' || field.type === 'integer';
  const inputType = numeric ? 'number' : 'text';
  const inputMode = field.type === 'integer' ? 'numeric' : numeric ? 'decimal' : undefined;
  const placeholder = numeric ? 'Enter value' : field.type === 'variation' ? `Enter ${field.label.toLocaleLowerCase()}` : `Enter ${field.label.toLocaleLowerCase()}`;
  const inputValue = value === null || value === undefined ? '' : value;
  const inputAttrs = numeric
    ? `min="${field.min ?? '0'}" step="${field.step || (field.type === 'integer' ? '1' : '0.01')}" inputmode="${inputMode}"`
    : field.type === 'variation' ? 'maxlength="500"' : 'spellcheck="false"';
  const width = field.type === 'variation' || field.key === 'description' ? 'form-field-wide' : '';
  return `<div class="form-field ${width}">${label}<input id="${fieldId}" name="${fieldKey}" type="${inputType}" value="${escapeHtml(inputValue)}" placeholder="${escapeHtml(placeholder)}" ${inputAttrs} ${required} />${hint}${error}</div>`;
}

export function renderFormGroups(product = null, variations = [], currencies = [], defaultCurrency = '') {
  return getFormGroups(variations).map((group) => `<section class="form-section" aria-labelledby="form-section-${escapeHtml(group.label.replace(/\s+/g, '-').toLocaleLowerCase())}"><div class="form-section-heading"><h3 id="form-section-${escapeHtml(group.label.replace(/\s+/g, '-').toLocaleLowerCase())}">${escapeHtml(group.label)}</h3><p>${escapeHtml(group.description)}</p></div><div class="form-fields">${group.fields.map((field) => renderField(field, product, { currencies, defaultCurrency })).join('')}</div></section>`).join('');
}
