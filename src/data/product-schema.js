import canonical from '../../shared/product-schema.json' with { type: 'json' };

export const CANONICAL_PRODUCT_SCHEMA = canonical;
export const STANDARD_PRODUCT_FIELDS = canonical.fields;
export const STANDARD_FIELD_KEYS = canonical.fields.map((field) => field.key);
export const PRODUCT_EXTENSIONS = canonical.extensions;
export const CATEGORIES = [
  'Phones', 'Electronics', 'Apparel', 'Clothing', 'Shoes', 'Home & Living', 'Beauty', 'Outdoor', 'Accessories',
];

const internalKeys = new Set(canonical.extensions.filter((field) => field.internal).map((field) => field.key));
const defaultVariations = [
  { key: 'Color', display_name: 'Color', active: true },
  { key: 'Size', display_name: 'Size', active: true },
];

export function getProductFields(variations = defaultVariations, { includeHidden = false } = {}) {
  const definitions = (variations || []).filter((item) => item.active !== false);
  const activeKeys = new Set(definitions.map((item) => item.key));
  const fields = STANDARD_PRODUCT_FIELDS
    .filter((field) => !internalKeys.has(field.key))
    .filter((field) => includeHidden || !field.hidden_by_default)
    .filter((field) => field.type !== 'variation' || activeKeys.has(field.key))
    .map((field) => ({
      ...field,
      group: field.form_group,
      systemManaged: field.editable === false,
      options: field.options || [],
      step: field.step || (field.type === 'integer' ? '1' : undefined),
      min: field.min ?? (['decimal', 'integer'].includes(field.type) ? '0' : undefined),
    }));

  for (const variation of definitions.filter((item) => !STANDARD_FIELD_KEYS.includes(item.key))) {
    fields.push({
      key: `variation:${variation.key}`,
      variationKey: variation.key,
      label: variation.display_name,
      type: variation.data_type || 'text',
      group: 'Product variations',
      form_group: 'Product variations',
      editable: true,
      required: false,
      nullable: true,
      searchable: true,
      sortable: true,
      width: 160,
    });
  }

  const extensions = PRODUCT_EXTENSIONS
    .filter((field) => !field.internal)
    .map((field) => ({
      ...field,
      group: field.form_group,
      systemManaged: field.editable === false,
      required: false,
      sortable: field.sortable !== false,
      searchable: field.key === 'tags',
      width: field.width || 150,
    }));
  const insertIndex = fields.findIndex((field) => field.key === 'created_at');
  fields.splice(insertIndex < 0 ? fields.length : insertIndex, 0, ...extensions);
  return fields;
}

export function getProductFieldByKey(variations = defaultVariations) {
  return Object.fromEntries(getProductFields(variations, { includeHidden: true }).map((field) => [field.key, field]));
}

export const PRODUCT_FIELDS = getProductFields(defaultVariations);
export const fieldByKey = getProductFieldByKey(defaultVariations);
